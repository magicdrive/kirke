package main

// End-to-end test of the generated code: the struct kirke generates for a
// JSON document is compiled into a program that decodes that same document
// with encoding/json, in both output modes.

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/magicdrive/kirke/internal/commandline"
	"github.com/magicdrive/kirke/internal/core"
)

const generatedProgram = `package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"math/big"
	"os"
)

var _ = big.NewInt

%s

func main() {
	data, err := os.ReadFile(os.Args[1])
	if err != nil {
		panic(err)
	}
	var v AutoGenerated
	if os.Args[2] == "usenumber" {
		dec := json.NewDecoder(bytes.NewReader(data))
		dec.UseNumber()
		err = dec.Decode(&v)
	} else {
		err = json.Unmarshal(data, &v)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	out, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	fmt.Println(string(out))
}
`

// TestGeneratedStruct_Unmarshal: JSON numbers with an exponent (1e3, 1E3,
// -2e+5, 0e0, 1e21, an underflow, nested, in an array element) decode
// into the struct generated for them with json.Unmarshal; a number beyond
// float64 (typed interface{}) decodes with a json.Decoder using UseNumber.
func TestGeneratedStruct_Unmarshal(t *testing.T) {
	if testing.Short() {
		t.Skip("builds Go programs")
	}
	for _, tc := range []struct {
		name, json, decode string
		want               []string // in the re-encoded document
	}{
		{
			name: "exponents",
			json: `{"a": 1e3, "b": 1E3, "c": -2e+5, "d": 0e0, "e": 1e21, "f": 1e-400,` +
				` "g": 5e-324, "i": 1, "x": 1.5, "s": "str", "n": {"e": 1e5}, "l": [{"e": 2e2}]}`,
			decode: "unmarshal",
			want:   []string{`"a":1000`, `"b":1000`, `"c":-200000`, `"d":0`, `"e":1e+21`, `"f":0`, `"g":5e-324`, `"e":100000`, `"e":200`},
		},
		{
			name:   "overflow",
			json:   `{"a": 1e400, "b": -1e309, "i": 2}`,
			decode: "usenumber",
			want:   []string{`"a":1e400`, `"b":-1e309`, `"i":2`},
		},
	} {
		for _, mode := range []int{commandline.OutputModeOutline, commandline.OutputModeInline} {
			t.Run(tc.name+map[int]string{commandline.OutputModeOutline: "/outline", commandline.OutputModeInline: "/inline"}[mode], func(t *testing.T) {
				src, err := core.Apply(tc.json, "AutoGenerated", mode, false, "any")
				if err != nil {
					t.Fatal(err)
				}
				dir := t.TempDir()
				write := func(name, content string) {
					if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
						t.Fatal(err)
					}
				}
				write("go.mod", "module generated\n\ngo 1.24\n")
				write("main.go", strings.Replace(generatedProgram, "%s", src, 1))
				write("input.json", tc.json)
				bin := filepath.Join(dir, "generated.exe")
				build := exec.Command("go", "build", "-o", bin, ".")
				build.Dir = dir
				build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off", "GOFLAGS=")
				if out, err := build.CombinedOutput(); err != nil {
					t.Fatalf("go build of the generated code: %v\n%s\n%s", err, out, src)
				}
				out, err := exec.Command(bin, filepath.Join(dir, "input.json"), tc.decode).CombinedOutput()
				if err != nil {
					t.Fatalf("decoding %s into the generated struct: %v\n%s\n%s", tc.json, err, out, src)
				}
				for _, w := range tc.want {
					if !strings.Contains(string(out), w) {
						t.Errorf("decoded document %s has no %s", out, w)
					}
				}
			})
		}
	}
}
