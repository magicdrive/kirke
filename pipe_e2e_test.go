package main

// End-to-end tests of `kirke --pipe` (and of JSON piped without --pipe): the
// kirke binary is built once and run with its standard input connected to a
// pipe, as a shell pipeline would.

import (
	"bytes"
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
	"sync"
	"syscall"
	"testing"
	"time"
)

var (
	pipeBinOnce sync.Once
	pipeBinPath string
	pipeBinErr  error
	pipeBinDir  string
)

func TestMain(m *testing.M) {
	code := m.Run()
	if pipeBinDir != "" {
		os.RemoveAll(pipeBinDir)
	}
	os.Exit(code)
}

// pipeTestBinary builds kirke once for every test in this file.
func pipeTestBinary(t *testing.T) string {
	t.Helper()
	pipeBinOnce.Do(func() {
		dir, err := os.MkdirTemp("", "kirke-pipe-e2e-")
		if err != nil {
			pipeBinErr = err
			return
		}
		pipeBinDir = dir
		bin := filepath.Join(dir, "kirke")
		if runtime.GOOS == "windows" {
			bin += ".exe"
		}
		cmd := exec.Command("go", "build", "-o", bin, "-ldflags", "-X main.version=v0.0.0-pipe-e2e", ".")
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0")
		if out, err := cmd.CombinedOutput(); err != nil {
			pipeBinErr = fmt.Errorf("go build: %v\n%s", err, out)
			return
		}
		pipeBinPath = bin
	})
	if pipeBinErr != nil {
		t.Fatal(pipeBinErr)
	}
	return pipeBinPath
}

type kirkeRun struct {
	stdout, stderr string
	err            error
}

// runKirke runs kirke with args, writing input to its standard input through
// a pipe (os/exec copies a non-*os.File reader through one) and closing it.
func runKirke(t *testing.T, input []byte, args ...string) kirkeRun {
	t.Helper()
	cmd := exec.Command(pipeTestBinary(t), args...)
	cmd.Env = kirkeTestEnv()
	cmd.Stdin = bytes.NewReader(input)
	var stdout, stderr bytes.Buffer
	cmd.Stdout, cmd.Stderr = &stdout, &stderr
	err := cmd.Run()
	return kirkeRun{stdout.String(), stderr.String(), err}
}

// kirkeTestEnv is the environment without the KIRKE_DEFAULT_* settings of the
// machine running the tests.
func kirkeTestEnv() []string {
	var env []string
	for _, kv := range os.Environ() {
		if !strings.HasPrefix(kv, "KIRKE_") {
			env = append(env, kv)
		}
	}
	return env
}

// collapseSpaces turns each run of spaces and tabs into one space, so that
// fields can be matched whatever gofmt's column alignment.
func collapseSpaces(s string) string {
	return regexp.MustCompile(`[ \t]+`).ReplaceAllString(s, " ")
}

func TestPipe_Input(t *testing.T) {
	const nameField = "Name string `json:\"name\"`"
	bigValue := strings.Repeat("x", 1<<20) // one line far beyond bufio.Scanner's 64 KiB token limit
	tests := []struct {
		name  string
		input string
		want  []string // substrings of the output
	}{
		{"no trailing newline", `{"name":"kirke"}`, []string{nameField}},
		{"trailing newline", "{\"name\":\"kirke\"}\n", []string{nameField}},
		{"multiple lines, last one without newline", "{\n  \"name\": \"kirke\",\n  \"age\": 3\n}", []string{nameField, "Age int `json:\"age\"`"}},
		{"multiple lines, last key on the unterminated line", "{\"name\": \"kirke\",\n\"last\": true}", []string{nameField, "Last bool `json:\"last\"`"}},
		{"CRLF", "{\r\n  \"name\": \"kirke\"\r\n}\r\n", []string{nameField}},
		{"CRLF without a final line break", "{\r\n  \"name\": \"kirke\"\r\n}", []string{nameField}},
		{"Unicode", `{"name":"キルケー","emoji":"🦉"}`, []string{nameField, "Emoji string `json:\"emoji\"`"}},
		{"invalid UTF-8 in a string value", "{\"name\":\"\xff\xfe\"}", []string{nameField}},
		{"one line over 64 KiB without newline", `{"name":"` + bigValue + `"}`, []string{nameField}},
		{"one line over 64 KiB with newline", `{"name":"` + bigValue + "\"}\n", []string{nameField}},
	}
	for _, tt := range tests {
		for _, args := range [][]string{{"--pipe", "--auto-pager", "off"}, {"--auto-pager", "off"}} {
			t.Run(tt.name+" "+strings.Join(args[:len(args)-2], ""), func(t *testing.T) {
				r := runKirke(t, []byte(tt.input), args...)
				if r.err != nil {
					t.Fatalf("kirke %v: %v\nstderr: %s", args, r.err, r.stderr)
				}
				if !strings.HasPrefix(r.stdout, "type AutoGenerated struct {\n") {
					t.Fatalf("unexpected output:\n%.500s", r.stdout)
				}
				for _, w := range tt.want {
					if !strings.Contains(collapseSpaces(r.stdout), w) {
						t.Errorf("output lacks %q:\n%.500s", w, r.stdout)
					}
				}
			})
		}
	}
}

// TestPipe_InvalidOrEmpty: what is not one JSON document fails with exit
// status 1, including an incomplete document whose end was cut off.
func TestPipe_InvalidOrEmpty(t *testing.T) {
	for _, in := range []string{"", "\n", `{"name":`, "{\"name\":\"kirke\"}\n{"} {
		r := runKirke(t, []byte(in), "--pipe", "--auto-pager", "off")
		var ee *exec.ExitError
		if !errors.As(r.err, &ee) || ee.ExitCode() != 1 {
			t.Errorf("input %q: want exit status 1, got %v (stdout %q)", in, r.err, r.stdout)
		}
		if !strings.Contains(r.stderr, "JSON string is corrupted") {
			t.Errorf("input %q: stderr %q", in, r.stderr)
		}
		if r.stdout != "" {
			t.Errorf("input %q: unexpected output %q", in, r.stdout)
		}
	}
}

// TestPipe_EmptyWithoutPipeFlag: without --pipe, empty piped input is no
// input: the usage is shown (as with no input at all), not an error.
func TestPipe_EmptyWithoutPipeFlag(t *testing.T) {
	r := runKirke(t, nil)
	if r.err != nil {
		t.Fatalf("kirke with empty input: %v\nstderr: %s", r.err, r.stderr)
	}
	if !strings.Contains(r.stdout, "Usage: kirke ") {
		t.Errorf("want the usage, got %q", r.stdout)
	}
}

// TestPipe_JSONOptionDoesNotReadStdin: with --json (or --file) and no --pipe,
// standard input is not read at all: kirke neither waits for it nor consumes
// it (`while read -r l; do kirke -j "$l"; done < list` keeps the rest of list).
func TestPipe_JSONOptionDoesNotReadStdin(t *testing.T) {
	dir := t.TempDir()
	file := filepath.Join(dir, "in.json")
	if err := os.WriteFile(file, []byte(`{"from_file":1}`), 0o644); err != nil {
		t.Fatal(err)
	}
	for _, args := range [][]string{
		{"-j", `{"from_json":1}`},
		{"-f", file},
	} {
		pr, pw, err := os.Pipe()
		if err != nil {
			t.Fatal(err)
		}
		cmd := exec.Command(pipeTestBinary(t), append(args, "--auto-pager", "off")...)
		cmd.Env = kirkeTestEnv()
		cmd.Stdin = pr // never written to and never closed while kirke runs
		var stdout, stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		pr.Close()
		done := make(chan error, 1)
		go func() { done <- cmd.Wait() }()
		select {
		case err := <-done:
			if err != nil {
				t.Errorf("kirke %v: %v\nstderr: %s", args, err, stderr.String())
			}
			if !strings.Contains(stdout.String(), "type AutoGenerated struct {") {
				t.Errorf("kirke %v: unexpected output %q", args, stdout.String())
			}
		case <-time.After(20 * time.Second):
			cmd.Process.Kill()
			<-done
			t.Errorf("kirke %v waits for standard input it does not use", args)
		}
		pw.Close()
	}
}

// TestPipe_NotStreaming: kirke converts one whole JSON document, so it writes
// nothing before standard input reaches EOF, even when a complete document
// has already arrived; the output follows the end of input.
func TestPipe_NotStreaming(t *testing.T) {
	cmd := exec.Command(pipeTestBinary(t), "--pipe", "--auto-pager", "off")
	cmd.Env = kirkeTestEnv()
	stdin, err := cmd.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	if _, err := io.WriteString(stdin, "{\"name\":\"kirke\"}\n"); err != nil {
		t.Fatal(err)
	}
	got := make(chan []byte, 1)
	go func() { b, _ := io.ReadAll(stdout); got <- b }()
	select {
	case b := <-got:
		t.Fatalf("output before EOF on standard input: %q", b)
	case <-time.After(500 * time.Millisecond):
	}
	stdin.Close()
	select {
	case b := <-got:
		if !strings.Contains(string(b), "Name string `json:\"name\"`") {
			t.Errorf("unexpected output %q", b)
		}
	case <-time.After(20 * time.Second):
		cmd.Process.Kill()
		t.Fatal("no output after EOF")
	}
	if err := cmd.Wait(); err != nil {
		t.Errorf("kirke: %v", err)
	}
}

// TestPipe_BrokenPipe: when the reader of kirke's output goes away (as with
// `kirke --pipe < big.json | head -1`), kirke stops instead of hanging.
func TestPipe_BrokenPipe(t *testing.T) {
	var in strings.Builder
	in.WriteString("{")
	for i := range 20000 {
		if i > 0 {
			in.WriteString(",")
		}
		fmt.Fprintf(&in, "\"field_number_%d\":%d", i, i)
	}
	in.WriteString("}") // no trailing newline
	cmd := exec.Command(pipeTestBinary(t), "--pipe", "--auto-pager", "off")
	cmd.Env = kirkeTestEnv()
	cmd.Stdin = strings.NewReader(in.String())
	stdout, err := cmd.StdoutPipe()
	if err != nil {
		t.Fatal(err)
	}
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	first := make([]byte, len("type AutoGenerated struct {"))
	if _, err := io.ReadFull(stdout, first); err != nil {
		t.Fatalf("reading the first bytes: %v (stderr: %s)", err, stderr.String())
	}
	if string(first) != "type AutoGenerated struct {" {
		t.Fatalf("unexpected output %q", first)
	}
	stdout.Close() // the reader goes away; the output (over 600 KB) cannot fit in a pipe buffer
	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()
	select {
	case err := <-done:
		if err == nil {
			t.Error("kirke reported success although its output was cut off")
		}
		if strings.Contains(stderr.String(), "panic") || strings.Contains(stderr.String(), "goroutine ") {
			t.Errorf("kirke crashed: %s", stderr.String())
		}
	case <-time.After(30 * time.Second):
		cmd.Process.Kill()
		<-done
		t.Fatal("kirke hangs after its reader went away")
	}
}

// TestPipe_Interrupted: kirke waiting for piped input is cancelled by SIGINT
// (Ctrl-C) and SIGTERM, prints nothing and exits unsuccessfully.
func TestPipe_Interrupted(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("no SIGINT/SIGTERM delivery to a child process on Windows")
	}
	for _, sig := range []os.Signal{os.Interrupt, syscall.SIGTERM} {
		cmd := exec.Command(pipeTestBinary(t), "--pipe", "--auto-pager", "off")
		cmd.Env = kirkeTestEnv()
		stdin, err := cmd.StdinPipe()
		if err != nil {
			t.Fatal(err)
		}
		var stdout bytes.Buffer
		cmd.Stdout = &stdout
		if err := cmd.Start(); err != nil {
			t.Fatal(err)
		}
		io.WriteString(stdin, "{\"name\":") // an incomplete document; stdin stays open
		time.Sleep(200 * time.Millisecond)
		if err := cmd.Process.Signal(sig); err != nil {
			t.Fatal(err)
		}
		done := make(chan error, 1)
		go func() { done <- cmd.Wait() }()
		select {
		case err := <-done:
			if err == nil {
				t.Errorf("%v: kirke exited successfully", sig)
			}
			if stdout.Len() != 0 {
				t.Errorf("%v: unexpected output %q", sig, stdout.String())
			}
		case <-time.After(20 * time.Second):
			cmd.Process.Kill()
			<-done
			t.Errorf("%v: kirke did not stop", sig)
		}
		stdin.Close()
	}
}

// TestPipe_ReadError: an error reading standard input is reported with its
// cause and exit status 1, not taken for "no input".
func TestPipe_ReadError(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("uses a directory as standard input")
	}
	dir, err := os.Open(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	defer dir.Close()
	for _, args := range [][]string{{"--pipe"}, {}} {
		cmd := exec.Command(pipeTestBinary(t), append(args, "--auto-pager", "off")...)
		cmd.Env = kirkeTestEnv()
		cmd.Stdin = dir // not a terminal, and read(2) fails with EISDIR
		var stdout, stderr bytes.Buffer
		cmd.Stdout, cmd.Stderr = &stdout, &stderr
		err := cmd.Run()
		var ee *exec.ExitError
		if !errors.As(err, &ee) || ee.ExitCode() != 1 {
			t.Errorf("kirke %v: want exit status 1, got %v", args, err)
		}
		if !strings.Contains(stderr.String(), "read standard input") || !strings.Contains(stderr.String(), "is a directory") {
			t.Errorf("kirke %v: stderr %q does not report the read error", args, stderr.String())
		}
		if stdout.Len() != 0 {
			t.Errorf("kirke %v: unexpected output %q", args, stdout.String())
		}
	}
}
