package main

// Exit status tests of make fmt-check and make smoke: a failing gofmt or
// kirke run fails the target, whatever it printed. Make runs each recipe
// line with sh -c (no -e, no pipefail), so a command substitution or a pipe
// into grep would otherwise drop the status.

import (
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strings"
	"testing"
)

// runMakeWithStubs runs make with the given arguments, the stubs directory
// first on PATH and without the variables of a parent make.
func runMakeWithStubs(t *testing.T, stubs string, env []string, args ...string) (string, error) {
	t.Helper()
	if runtime.GOOS == "windows" {
		t.Skip("the Makefile targets macOS and Linux")
	}
	if _, err := exec.LookPath("make"); err != nil {
		t.Skip("make not installed")
	}
	cmd := exec.Command("make", append([]string{"--no-print-directory"}, args...)...)
	for _, kv := range os.Environ() {
		k, _, _ := strings.Cut(kv, "=")
		if !slices.Contains([]string{"MAKEFLAGS", "MFLAGS", "MAKELEVEL", "PATH"}, k) {
			cmd.Env = append(cmd.Env, kv)
		}
	}
	cmd.Env = append(cmd.Env, env...)
	cmd.Env = append(cmd.Env, "PATH="+stubs+string(os.PathListSeparator)+os.Getenv("PATH"))
	out, err := cmd.CombinedOutput()
	return string(out), err
}

func writeStub(t *testing.T, path, script string) {
	t.Helper()
	if err := os.WriteFile(path, []byte("#!/bin/sh\n"+script+"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
}

// TestMakefile_FmtCheckFailsWhenGofmtFails: gofmt prints nothing on stdout
// when it fails (a file it cannot parse, no gofmt on PATH); that must not
// read as "every file is formatted".
func TestMakefile_FmtCheckFailsWhenGofmtFails(t *testing.T) {
	for _, tc := range []struct {
		name, gofmt string
		ok          bool
	}{
		{"formatted", "exit 0", true},
		{"unformatted", "echo main.go", false},
		{"gofmt fails", `echo "broken.go:1:1: expected 'package', found 'EOF'" >&2; exit 2`, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			stubs := t.TempDir()
			writeStub(t, filepath.Join(stubs, "gofmt"), tc.gofmt)
			out, err := runMakeWithStubs(t, stubs, nil, "fmt-check")
			if (err == nil) != tc.ok {
				t.Errorf("make fmt-check: err %v, want ok %t\n%s", err, tc.ok, out)
			}
		})
	}
}

// TestMakefile_SmokeChecksTheExitStatus runs make smoke (without its build
// prerequisite) on a stub kirke that prints the expected output of every
// smoke command but exits 1 for one of them: the target must fail.
func TestMakefile_SmokeChecksTheExitStatus(t *testing.T) {
	for _, fail := range []string{"", "--version", "--help", "--pipe"} {
		t.Run("fail="+fail, func(t *testing.T) {
			dir := t.TempDir()
			writeStub(t, filepath.Join(dir, "kirke"), `case "$1" in
--version) echo "kirke version v0.0.0-test" ;;
--help) echo "Usage: kirke [options]" ;;
--pipe) cat >/dev/null; echo "type AutoGenerated struct {" ;;
esac
[ "$1" = "$STUB_FAIL" ] && exit 1
exit 0`)
			out, err := runMakeWithStubs(t, t.TempDir(), []string{"STUB_FAIL=" + fail}, "-o", "build", "smoke", "BUILD_DIR="+dir, "VERSION=v0.0.0-test")
			if (err == nil) != (fail == "") {
				t.Errorf("make smoke with %s failing: err %v\n%s", fail, err, out)
			}
		})
	}
}
